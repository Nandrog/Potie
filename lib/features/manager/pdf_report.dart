import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../core/format.dart';
import '../../core/models.dart';
import '../print/print_service.dart';

class ReportOptions {
  bool payments = true;
  bool waiters = true;
  bool movements = true;
  bool extensions = true;
  bool audit = true;
  bool outstanding = true;
}

Future<Uint8List> buildReport({
  required String title,
  required String currency,
  required DateTime from,
  required DateTime to,
  required List<PotToken> tokens,
  required List<AuditEntry> audit,
  required ReportOptions options,
  required String generatedBy,
}) async {
  final doc = pw.Document(title: title, author: generatedBy);
  final logo = await loadLogo();
  String m(num v) => '$currency ${money(v)}';

  // Only money actually received counts as collected.
  double paidBy(PayMethod pm, Iterable<PotToken> ts) {
    var s = 0.0;
    for (final t in ts) {
      if (t.method == pm && t.paid) s += t.amount;
      for (final e in t.extensions) {
        if (e.method == pm && e.confirmed) s += e.fee;
      }
    }
    return s;
  }

  final total = tokens.fold<double>(0, (s, t) => s + t.collected);
  final unpaid = tokens.where((t) => !t.paid).toList();
  final owed = unpaid.fold<double>(0, (s, t) => s + t.amount);
  final waiterNames = tokens.map((t) => t.waiterName).toSet().toList()..sort();

  pw.Widget h(String text) => pw.Padding(
        padding: const pw.EdgeInsets.only(top: 18, bottom: 6),
        child: pw.Text(text,
            style: const pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold)),
      );

  pw.Widget table(List<String> head, List<List<String>> rows) =>
      pw.TableHelper.fromTextArray(
        headers: head,
        data: rows,
        headerStyle: const pw.TextStyle(
            fontWeight: pw.FontWeight.bold, fontSize: 9, color: PdfColors.white),
        headerDecoration: const pw.BoxDecoration(color: PdfColors.grey800),
        cellStyle: const pw.TextStyle(fontSize: 8.5),
        cellAlignment: pw.Alignment.centerLeft,
        rowDecoration: const pw.BoxDecoration(
            border: pw.Border(bottom: pw.BorderSide(color: PdfColors.grey300))),
      );

  doc.addPage(pw.MultiPage(
    pageFormat: PdfPageFormat.a4,
    margin: const pw.EdgeInsets.all(32),
    footer: (c) => pw.Align(
      alignment: pw.Alignment.centerRight,
      child: pw.Text('Page ${c.pageNumber}/${c.pagesCount}',
          style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600)),
    ),
    build: (_) => [
      if (logo != null)
        pw.Align(
          alignment: pw.Alignment.centerLeft,
          child: pw.Image(logo, height: 70),
        )
      else
        pw.Text(businessName,
            style: const pw.TextStyle(fontSize: 11, color: PdfColors.grey700)),
      pw.SizedBox(height: 6),
      pw.Text(title,
          style: const pw.TextStyle(fontSize: 22, fontWeight: pw.FontWeight.bold)),
      pw.Text('${dateOnly(from)} - ${dateOnly(to)}   ·   generated by $generatedBy on ${dateTime(DateTime.now())}',
          style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600)),
      pw.SizedBox(height: 10),
      pw.Row(children: [
        _kpi('Tokens', '${tokens.length}'),
        _kpi('Total collected', m(total)),
        _kpi('Outstanding', m(owed)),
        _kpi('Waiters', '${waiterNames.length}'),
        _kpi('Extensions',
            '${tokens.fold<int>(0, (s, t) => s + t.extensions.length)}'),
      ]),
      if (options.payments) ...[
        h('Payments by method'),
        table(['Method', 'Amount'], [
          for (final pm in PayMethod.values) [pm.label, m(paidBy(pm, tokens))],
          ['Total', m(total)],
        ]),
      ],
      if (options.waiters) ...[
        h('Waiter performance'),
        table(
          ['Waiter', 'Tokens', 'Extensions', 'Collected'],
          [
            for (final w in waiterNames)
              () {
                final ts = tokens.where((t) => t.waiterName == w).toList();
                return [
                  w,
                  '${ts.length}',
                  '${ts.fold<int>(0, (s, t) => s + t.extensions.length)}',
                  m(ts.fold<double>(0, (s, t) => s + t.collected)),
                ];
              }(),
          ],
        ),
      ],
      if (options.movements) ...[
        h('Pot movements'),
        table(
          ['Pot', 'Waiter', 'Distributor', 'Issued', 'Out', 'Back', 'Time', 'Paid', 'Method'],
          [
            for (final t in tokens)
              [
                t.potLabel ?? '-',
                t.waiterName,
                t.distributorName ?? '-',
                dateTime(t.issuedAt),
                t.clearedAt == null ? '-' : hm(t.clearedAt!),
                t.returnedAt == null ? '-' : hm(t.returnedAt!),
                minutesLabel(t.totalMinutes),
                money(t.collected),
                t.paid ? t.method.label : 'UNPAID',
              ],
          ],
        ),
      ],
      if (options.outstanding) ...[
        h('Outstanding payments'),
        unpaid.isEmpty
            ? pw.Text('Everything in this period has been paid.',
                style: const pw.TextStyle(fontSize: 9))
            : table(
                ['Pot', 'Waiter', 'Option', 'Out', 'Pay by', 'Amount', 'Status'],
                [
                  for (final t in unpaid)
                    [
                      t.potLabel ?? '-',
                      t.waiterName,
                      t.payTiming.label,
                      t.clearedAt == null ? '-' : dateTime(t.clearedAt!),
                      t.payDueAt == null ? '-' : dateTime(t.payDueAt!),
                      money(t.amount),
                      t.paymentOverdue ? 'OVERDUE' : 'Pending',
                    ],
                ],
              ),
      ],
      if (options.extensions) ...[
        h('Extensions'),
        () {
          final rows = [
            for (final t in tokens)
              for (final e in t.extensions)
                [
                  t.potLabel ?? '-',
                  t.waiterName,
                  dateTime(e.at),
                  '+${e.minutes} min',
                  money(e.fee),
                  e.method.label,
                  e.confirmed ? 'Yes' : 'No',
                ]
          ];
          return rows.isEmpty
              ? pw.Text('None in this period.',
                  style: const pw.TextStyle(fontSize: 9))
              : table(['Pot', 'Waiter', 'When', 'Extra', 'Fee', 'Method', 'Confirmed'], rows);
        }(),
      ],
      if (options.audit) ...[
        h('Audit trail'),
        audit.isEmpty
            ? pw.Text('No entries.', style: const pw.TextStyle(fontSize: 9))
            : table(
                ['When', 'Who', 'Role', 'Action', 'Detail'],
                [
                  for (final a in audit)
                    [
                      dateTime(a.at),
                      a.actorName,
                      a.actorRole.label,
                      a.action.replaceAll('_', ' '),
                      a.detail.replaceAll('→', '->'),
                    ],
                ],
              ),
      ],
    ],
  ));
  return doc.save();
}

pw.Widget _kpi(String label, String value) => pw.Expanded(
      child: pw.Container(
        margin: const pw.EdgeInsets.only(right: 8),
        padding: const pw.EdgeInsets.all(8),
        decoration: pw.BoxDecoration(
          border: pw.Border.all(color: PdfColors.grey400),
          borderRadius: pw.BorderRadius.circular(4),
        ),
        child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
          pw.Text(label,
              style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600)),
          pw.Text(value,
              style: const pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold)),
        ]),
      ),
    );
